// Helper: Calculate geodetic distance in Kilometers using Haversine formula
export function calculateHaversineDistance(lat1, lon1, lat2, lon2) {
  const R = 6371; // Radius of Earth in KM
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return parseFloat((R * c).toFixed(1));
}

// Find closest AP District given GPS coordinates
export function findClosestAPDistrict(lat, lng) {
  let closest = apDistricts[21]; // Default: Tirupati
  let minDistance = Infinity;

  for (const district of apDistricts) {
    const dist = calculateHaversineDistance(lat, lng, district.lat, district.lng);
    if (dist < minDistance) {
      minDistance = dist;
      closest = { ...district, distanceKm: dist };
    }
  }

  return closest;
}
